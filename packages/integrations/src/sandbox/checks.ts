import {
  feedReadRequestSchema,
  feedReadResponseSchema,
  fileProcessRequestSchema,
  fileProcessResponseSchema,
  type FeedReadRequest,
  type FeedReadResponse,
  type FileProcessRequest,
  type FileProcessResponse,
} from "./protocol.js";

/**
 * Request and response checks shared by the sandbox adapters (research R2). A failed check
 * becomes an error code; the Zod issues are dropped, because they can quote the input.
 */
export type Checked<Request, Response> = { request: Request } | { response: Response };

/**
 * A link that is not an HTTPS URL is refused with `not_https` before any function runs
 * (SEC-09). Any other mismatch is a caller bug and returns `internal`.
 */
export function checkFeedRequest(request: unknown): Checked<FeedReadRequest, FeedReadResponse> {
  const parsed = feedReadRequestSchema.safeParse(request);
  if (parsed.success) return { request: parsed.data };
  const badLink = parsed.error.issues.some(
    (issue) => issue.path[0] === "url" && issue.code === "invalid_format",
  );
  return { response: { error: badLink ? "not_https" : "internal" } };
}

/** A response that does not match the protocol exactly returns `internal`. */
export function checkFeedResponse(payload: unknown): FeedReadResponse {
  const parsed = feedReadResponseSchema.safeParse(payload);
  return parsed.success ? parsed.data : { error: "internal" };
}

/** Object keys are generated by the API, so an invalid request is a bug: `internal`. */
export function checkFileRequest(
  request: unknown,
): Checked<FileProcessRequest, FileProcessResponse> {
  const parsed = fileProcessRequestSchema.safeParse(request);
  return parsed.success ? { request: parsed.data } : { response: { error: "internal" } };
}

/**
 * A response that does not match the protocol, or that does not fit the purpose (rows for a
 * screenshot, text for a CSV file), returns `internal`.
 */
export function checkFileResponse(
  purpose: FileProcessRequest["purpose"],
  payload: unknown,
): FileProcessResponse {
  const parsed = fileProcessResponseSchema.safeParse(payload);
  if (!parsed.success) return { error: "internal" };
  const response = parsed.data;
  if (purpose === "screenshot" && "rows" in response) return { error: "internal" };
  if (purpose === "csv" && "text" in response) return { error: "internal" };
  return response;
}
