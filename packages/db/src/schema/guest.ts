/**
 * The guest guide (feature 004 data model §1–§4): property links, stay links, guest device
 * sessions, and daily open counts. RLS policies, column grants, and the stay check live in
 * migration 0022.
 *
 * Every table is tenant-owned (`workspace_id`), with RLS enabled and forced (SEC-14). Stay tokens
 * and confirmation codes are stored as vault ciphertext (and the token also as a SHA-256 hash for
 * lookup); session cookies only as hashes. No table holds a network address or device detail.
 */
import { sql } from "drizzle-orm";
import {
  check,
  date,
  index,
  integer,
  pgTable,
  primaryKey,
  smallint,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";
import { user } from "./auth.js";
import { bytea, createdAt, inList } from "./columns.js";
import { workspaceDataKey } from "./keys.js";
import { property } from "./properties.js";
import { stay } from "./stays.js";
import { workspace } from "./tenancy.js";

export const GUIDE_LINK_STATUSES = ["active", "replaced"] as const;
export const STAY_LINK_STATUSES = ["active", "revoked", "replaced"] as const;
export const GUIDE_OPEN_KINDS = ["property", "stay"] as const;

/** The property link: the public address of a property's guide (FR-017). */
export const guideLink = pgTable(
  "guide_link",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    workspaceId: uuid("workspace_id")
      .notNull()
      .references(() => workspace.id, { onDelete: "cascade" }),
    propertyId: uuid("property_id")
      .notNull()
      .references(() => property.id, { onDelete: "cascade" }),
    publicId: text("public_id").notNull(),
    status: text("status", { enum: GUIDE_LINK_STATUSES }).notNull().default("active"),
    createdBy: text("created_by").references(() => user.id, { onDelete: "set null" }),
    createdAt: createdAt(),
    replacedAt: timestamp("replaced_at", { withTimezone: true }),
    replacedBy: text("replaced_by").references(() => user.id, { onDelete: "set null" }),
  },
  (t) => [
    uniqueIndex("guide_link_public_id_uq").on(t.publicId),
    uniqueIndex("guide_link_active_uq")
      .on(t.propertyId)
      .where(sql`${t.status} = 'active'`),
    index("guide_link_workspace_idx").on(t.workspaceId),
    check("guide_link_public_id_format", sql`${t.publicId} ~ '^[a-z2-7]{26}$'`),
    check("guide_link_status_valid", inList(t.status, GUIDE_LINK_STATUSES)),
    check(
      "guide_link_replaced_consistent",
      sql`(${t.status} = 'replaced') = (${t.replacedAt} IS NOT NULL)`,
    ),
  ],
);

/** The per-stay link that unlocks locked fields inside the stay window (FR-020, SEC-01). */
export const stayLink = pgTable(
  "stay_link",
  {
    /** Generated by the application before encrypting: the vault AAD binds the row ID. */
    id: uuid("id").primaryKey(),
    workspaceId: uuid("workspace_id")
      .notNull()
      .references(() => workspace.id, { onDelete: "cascade" }),
    propertyId: uuid("property_id")
      .notNull()
      .references(() => property.id, { onDelete: "cascade" }),
    stayId: uuid("stay_id")
      .notNull()
      .references(() => stay.id, { onDelete: "cascade" }),
    tokenHash: text("token_hash").notNull(),
    /** Restricted: never selectable by guidesk_app (migration 0022). */
    tokenCiphertext: bytea("token_ciphertext").notNull(),
    dataKeyId: uuid("data_key_id")
      .notNull()
      .references(() => workspaceDataKey.id),
    /** Restricted: the stay's confirmation code, when the property requires one (FR-034). */
    confirmationCiphertext: bytea("confirmation_ciphertext"),
    status: text("status", { enum: STAY_LINK_STATUSES }).notNull().default("active"),
    createdBy: text("created_by").references(() => user.id, { onDelete: "set null" }),
    createdAt: createdAt(),
    lastCopiedAt: timestamp("last_copied_at", { withTimezone: true }),
    lastCopiedBy: text("last_copied_by").references(() => user.id, { onDelete: "set null" }),
    endedAt: timestamp("ended_at", { withTimezone: true }),
    endedBy: text("ended_by").references(() => user.id, { onDelete: "set null" }),
    /** Wrong codes in the current 15-minute window, across every device (research R8). */
    failureCount: smallint("failure_count").notNull().default(0),
    failureWindowStartedAt: timestamp("failure_window_started_at", { withTimezone: true }),
    lockedUntil: timestamp("locked_until", { withTimezone: true }),
    lockoutCount: smallint("lockout_count").notNull().default(0),
    lastLockoutAt: timestamp("last_lockout_at", { withTimezone: true }),
  },
  (t) => [
    uniqueIndex("stay_link_token_hash_uq").on(t.tokenHash),
    uniqueIndex("stay_link_active_uq")
      .on(t.stayId)
      .where(sql`${t.status} = 'active'`),
    index("stay_link_property_idx").on(t.propertyId, t.status),
    index("stay_link_workspace_idx").on(t.workspaceId),
    check("stay_link_token_hash_format", sql`${t.tokenHash} ~ '^[0-9a-f]{64}$'`),
    check("stay_link_status_valid", inList(t.status, STAY_LINK_STATUSES)),
    check("stay_link_ended_consistent", sql`(${t.status} = 'active') = (${t.endedAt} IS NULL)`),
    check("stay_link_counts", sql`${t.failureCount} >= 0 AND ${t.lockoutCount} >= 0`),
  ],
);

/** One guest device's session from a stay link (research R5). Hashes only; no device details. */
export const guideSession = pgTable(
  "guide_session",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    workspaceId: uuid("workspace_id")
      .notNull()
      .references(() => workspace.id, { onDelete: "cascade" }),
    propertyId: uuid("property_id")
      .notNull()
      .references(() => property.id, { onDelete: "cascade" }),
    stayLinkId: uuid("stay_link_id")
      .notNull()
      .references(() => stayLink.id, { onDelete: "cascade" }),
    cookieHash: text("cookie_hash").notNull(),
    verifiedAt: timestamp("verified_at", { withTimezone: true }),
    createdAt: createdAt(),
    lastSeenAt: timestamp("last_seen_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    uniqueIndex("guide_session_cookie_hash_uq").on(t.cookieHash),
    index("guide_session_link_idx").on(t.stayLinkId),
    index("guide_session_workspace_idx").on(t.workspaceId),
    check("guide_session_cookie_hash_format", sql`${t.cookieHash} ~ '^[0-9a-f]{64}$'`),
  ],
);

/** Guide opens per property, day (property's zone), and link kind. Counts only (FR-049, FR-050). */
export const guideOpenDaily = pgTable(
  "guide_open_daily",
  {
    workspaceId: uuid("workspace_id")
      .notNull()
      .references(() => workspace.id, { onDelete: "cascade" }),
    propertyId: uuid("property_id")
      .notNull()
      .references(() => property.id, { onDelete: "cascade" }),
    day: date("day").notNull(),
    linkKind: text("link_kind", { enum: GUIDE_OPEN_KINDS }).notNull(),
    opens: integer("opens").notNull().default(0),
  },
  (t) => [
    primaryKey({ columns: [t.propertyId, t.day, t.linkKind] }),
    index("guide_open_daily_workspace_idx").on(t.workspaceId),
    check("guide_open_daily_kind_valid", inList(t.linkKind, GUIDE_OPEN_KINDS)),
    check("guide_open_daily_opens", sql`${t.opens} >= 0`),
  ],
);
